# 4) Create a tuple: marks = (80, 90, 75, 90, 85, 90)

# Find:
# 1. How many times 90 appears.
# 2. The index of 75.
# 3. The highest mark.
# 4. The lowest mark.
# 5. The total marks.

marks = (80, 90, 75, 90, 85, 90)

print(marks.count(90))
print(marks.index(75))
print(max(marks))
print(min(marks))
print(sum(marks))